#!/usr/bin/env python3
"""Generate test/support/ota_vectors.h: a deterministic Ed25519 test vector for the
OTA signature tests. The keys are derived from fixed strings and are TEST KEYS ONLY:
nothing here is ever used by the firmware. Run it again to regenerate the header; the
output is byte-for-byte stable.

The payload layout is written out independently of the C++ code so the tests compare
two implementations:
  "PLANERADAR-OTA-v1\\0" (18) || sha256 (32) || build (4, BE) || min_build (4, BE)
  || channel (1: prod 0x01, rc 0x02) || id (32; zeros for prod, for rc the board's
  16-byte device hash followed by 16 zero bytes)
"""
import base64
import hashlib
import struct
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

PREFIX = b"PLANERADAR-OTA-v1\0"
DEVID_PREFIX = b"PLANERADAR-DEVID-v1\0"


def key(label: bytes) -> Ed25519PrivateKey:
    return Ed25519PrivateKey.from_private_bytes(hashlib.sha256(label).digest())


def public_bytes(k: Ed25519PrivateKey) -> bytes:
    return k.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)


def rc_id(device_id: bytes) -> bytes:
    """The payload's id field for rc: the 16-byte published hash, zero-padded to 32 bytes."""
    return device_id[:16] + bytes(16)


def payload(sha: bytes, build: int, min_build: int, channel: int, device_id: bytes) -> bytes:
    out = PREFIX + sha + struct.pack(">II", build, min_build) + bytes([channel]) + device_id
    assert len(out) == 91
    return out


def b64sig(k: Ed25519PrivateKey, data: bytes) -> str:
    return base64.b64encode(k.sign(data)).decode()


def arr(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 8]) for i in range(0, len(data), 8)]
    return f"constexpr uint8_t {name}[{len(data)}] = {{\n  " + ",\n  ".join(rows) + "};\n"


def main() -> None:
    signer = key(b"planeradar ota test key")
    other = key(b"planeradar ota other key")
    sha = hashlib.sha256(b"planeradar test firmware image").digest()
    mac = bytes.fromhex("a1b2c3d4e5f6")
    device_id = hashlib.sha256(DEVID_PREFIX + mac).digest()
    build, min_build = 8, 5
    prod = payload(sha, build, min_build, 0x01, bytes(32))
    rc = payload(sha, build, min_build, 0x02, rc_id(device_id))

    text = "// Generated by scripts/make_ota_test_vector.py. TEST KEYS ONLY: never used by the firmware.\n"
    text += "#pragma once\n\n#include <cstddef>\n#include <cstdint>\n\nnamespace ota_vectors {\n\n"
    text += arr("kPub", public_bytes(signer)) + arr("kOtherPub", public_bytes(other))
    text += arr("kMac", mac) + arr("kDeviceId", device_id) + arr("kSha", sha)
    text += arr("kPayloadProd", prod) + arr("kPayloadRc", rc)
    text += f'\nconstexpr char kShaHex[] = "{sha.hex()}";\n'
    text += f"constexpr uint32_t kBuild = {build};\nconstexpr uint32_t kMinBuild = {min_build};\n"
    text += f'constexpr char kSigProd[] = "{b64sig(signer, prod)}";\n'
    text += f'constexpr char kSigRc[] = "{b64sig(signer, rc)}";\n'
    text += f'constexpr char kSigWrongKey[] = "{b64sig(other, prod)}";\n'
    # A multi-chunk image (5000 bytes: two full 2 KB reads plus a remainder), signed as prod
    # build 8 min_build 5. The C++ tests build the same bytes from kBigImageByte(i).
    big = bytes(((i * 7 + 3) & 0xFF) for i in range(5000))
    big_sha = hashlib.sha256(big).digest()
    big_prod = payload(big_sha, build, min_build, 0x01, bytes(32))
    big_rc = payload(big_sha, build + 1, min_build, 0x02, rc_id(device_id))
    text += f'\nconstexpr char kBigShaHex[] = "{big_sha.hex()}";\n'
    text += "constexpr size_t kBigImageBytes = 5000;\n"
    text += "constexpr uint8_t kBigImageByte(size_t i) { return static_cast<uint8_t>((i * 7 + 3) & 0xFF); }\n"
    text += f'constexpr char kBigSigProd[] = "{b64sig(signer, big_prod)}";\n'
    text += f'constexpr uint32_t kBigRcBuild = {build + 1};\n'
    big_prod9 = payload(big_sha, build + 1, min_build, 0x01, bytes(32))
    text += f'constexpr char kBigSigProdBuild9[] = "{b64sig(signer, big_prod9)}";\n'
    text += f'constexpr char kBigSigRc[] = "{b64sig(signer, big_rc)}";\n'
    # Release-candidate variants for the same small image: an older rc build, and an rc
    # signed for a different board.
    other_id = hashlib.sha256(DEVID_PREFIX + bytes.fromhex("010203040506")).digest()
    text += f"\nconstexpr uint32_t kOldRcBuild = {build - 1};\n"
    text += f'constexpr char kSigOldRc[] = "{b64sig(signer, payload(sha, build - 1, min_build, 0x02, rc_id(device_id)))}";\n'
    text += f'constexpr char kSigRcOtherBoard[] = "{b64sig(signer, payload(sha, build, min_build, 0x02, rc_id(other_id)))}";\n'
    text += "\n}  // namespace ota_vectors\n"
    Path(__file__).resolve().parent.parent.joinpath("test/support/ota_vectors.h").write_text(text)


if __name__ == "__main__":
    main()
